#!/usr/bin/env python3
"""Write docs/verification-results.md from a verify run and the acceptance tolerances.

    python tools/report.py VERIFY_OUT [--acceptance docs/acceptance.md]
                           [--out docs/verification-results.md]

VERIFY_OUT is the folder tools/verify.py wrote (results.json and run.json). The report is
generated, never edited by hand: every number in it comes from the run, and the run's commit,
machine and date head it, so a reader can tell what it describes and whether it is current.
Interpretation belongs in docs/verification.md, which cites this file.

Each case is assessed against docs/acceptance.md where a tolerance is set, and marked "not
assessed" where none is. No tolerance is ever assumed. Also written: the same results as JSON
(OUT with .json), without r2c's records.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(Path(__file__).resolve().parent))
GENERATED = ("<!-- Generated by tools/report.py from a tools/verify.py run. Do not edit: "
             "rerun verify and report instead. -->")


def read_acceptance(path: Path) -> dict:
    """The toml block of docs/acceptance.md."""
    text = path.read_text(encoding="utf-8")
    m = re.search(r"```toml\n(.*?)```", text, re.S)
    if not m:
        raise SystemExit(f"{path}: no ```toml block")
    return tomllib.loads(m.group(1))


def group(ref: dict) -> str:
    inc = [float(x) for x in ref["increment"].split(",")]
    ini = [float(x) for x in ref["initial"].split(",")]
    return "shear" if inc[2] != 0.0 or ini[2] != 0.0 else "flexure"


def assess(res: dict, acc: dict) -> dict:
    """{check: (value, limit, ok)} for each tolerance that is set; ok is None if unset."""
    g = group(res["ref"])
    lim = acc.get(g, {})
    out = {}
    c = res["control"][-1] if res.get("control") else None
    if c:
        d = c["peak_diff_pct"]
        hi = lim.get("peak_pct_high")
        if d > 0 and hi is not None:
            out["peak"] = (d, hi, abs(d) <= hi)
        elif lim.get("peak_pct") is not None:
            out["peak"] = (d, lim["peak_pct"], abs(d) <= lim["peak_pct"])
        else:
            out["peak"] = (d, None, None)
        fl = c.get("floor_pct", 0.0)
        cv = c.get("rising_pct", c.get("curve_max_diff_pct"))
        if cv is not None:
            cl = lim.get("curve_pct")
            out["curve"] = (cv, cl, None if cl is None else cv <= max(cl, fl))
        pv = c.get("post_peak_pct")
        if pv is not None:
            pl = lim.get("post_peak_pct")
            out["post_peak"] = (pv, pl, None if pl is None else pv <= max(pl, fl))
        if "shape_same" in c:
            out["shape"] = (c["shape_same"], True, c["shape_same"])
    vacc = acc.get("views", {})
    exempt = set(vacc.get("views_exempt", []))
    # a view within the printed-precision floor counts as no difference
    vals = [0.0 if v["max_diff"] <= v.get("floor", 0.0) else v["max_diff_pct"]
            for v in res.get("views", [])
            if not v.get("missing") and v["view"] not in exempt]
    if vals:
        vw = max(vals)
        vl = vacc.get("views_pct")
        out["views"] = (vw, vl, None if vl is None else vw <= vl)
    return out


def verdict(checks: dict) -> str:
    oks = [ok for _v, _l, ok in checks.values()]
    if any(ok is False for ok in oks):
        return "outside: " + ", ".join(NAMES.get(k, k) for k, (_v, _l, ok) in checks.items()
                                       if ok is False)
    if oks and all(ok is True for ok in oks):
        return "within"
    if any(ok is True for ok in oks):
        return "within, partly assessed"
    return "not assessed"


NAMES = {"curve": "rising", "post_peak": "post-peak"}


def label(ref: dict) -> str:
    """The case in engineering terms (tools/dashboard.py, label)."""
    import dashboard
    return dashboard.label(ref)


def cell(check, signed=True) -> str:
    if check is None:
        return ""
    v, lim, ok = check
    s = f"{v:+.2f}" if signed else f"{v:.2f}"
    if ok is None:
        return s
    return f"{s} {'≤' if ok else '>'} {lim:g}"


def shape_cell(c) -> str:
    if "shape_same" not in c:
        return ""
    if c["shape_same"]:
        return "same"
    return f"different: Resp. {', '.join(c['shape_ref'])}; r2c {', '.join(c['shape_sub'])}"


def render(results: dict, run: dict, acc: dict, acc_path: str) -> str:
    out = [GENERATED, "", "# Verification results", ""]
    commit = run.get("commit", "")[:12] + (" (uncommitted changes)" if run.get("dirty") else "")
    out += [
        f"- r2c {run.get('r2c_version')} at commit `{commit}`",
        f"- Run {run.get('started')} on {run.get('host')} ({run.get('machine')}), "
        f"Python {run.get('python')}, numpy {run.get('numpy')}, {run.get('jobs')} case(s) at "
        f"a time",
        f"- Reference: the oracle fixtures (`{run.get('reference_dir')}`), captured from "
        "Response-2000 1.9.7 with r2x",
        f"- Tolerances: `{acc_path}`"
        + ("" if any(acc.get(k) for k in acc) else " (none set: nothing is assessed)"),
        "",
        "Times are measured wall-clock seconds for r2c on that machine. Nothing here times "
        "Response.",
        "",
    ]
    ran = {k: v for k, v in results.items() if "control" in v}
    skipped = {k: v for k, v in results.items() if "control" not in v}
    for g, title in (("flexure", "Without shear"), ("shear", "With shear")):
        names = sorted(n for n, r in ran.items() if group(r["ref"]) == g)
        if not names:
            continue
        out += [f"## {title}", "",
                "| Case | Input | Initial; increment | Stages Resp. / r2c | Chart | "
                "Peak Resp. | Peak r2c | Peak diff % | Rising % | Post-peak % | Shape | "
                "Views % (worst) | Assessment | Time s |",
                "|---|---|---|---|---|---:|---:|---:|---:|---:|---|---:|---|---:|"]
        for n in names:
            r = ran[n]
            h = r["ref"]
            c = r["control"][-1]
            chk = assess(r, acc)
            worst = ""
            if r.get("views"):
                vv = [v for v in r["views"] if not v.get("missing")]
                if vv:
                    w = max(vv, key=lambda v: v["max_diff_pct"])
                    worst = f"{w['max_diff_pct']:.1f} ({w['view']})"
            inp = h["input-name"]
            extra = []
            if h.get("units") not in (None, "si"):
                extra.append(h["units"])
            if h.get("factors") not in (None, "1.00,1.00,1.00"):
                extra.append("CSA")
            if h.get("more-detail") not in (None, "0"):
                extra.append(f"MD×{h['more-detail']}")
            if extra:
                inp += " " + " ".join(extra)
            out.append(
                f"| {n}: {label(h)} | {inp} | {h['initial']}; {h['increment']} | "
                f"{h['stage-count']} / {r['sub']['stage-count']} | {c['chart']} | "
                f"{c['ref_peak_load']:.1f} | {c['sub_peak_load']:.1f} | "
                f"{cell(chk.get('peak'))} | {cell(chk.get('curve'), signed=False)} | "
                f"{cell(chk.get('post_peak'), signed=False)} | {shape_cell(c)} | {worst} | "
                f"{verdict(chk)} | {r.get('seconds', '')} |")
        out.append("")
    if skipped:
        out += ["## Not run", ""]
        for n in sorted(skipped):
            out.append(f"- {n}: {skipped[n].get('skipped') or skipped[n].get('failed')}")
        out.append("")
    # the detail views, worst case per view
    rows = {}
    for n, r in ran.items():
        for v in r.get("views", []):
            if v.get("missing"):
                continue
            k = v["view"]
            if k not in rows or v["max_diff_pct"] > rows[k][0]:
                rows[k] = (v["max_diff_pct"], n)
    if rows:
        out += ["## Detail views at the features of the curve, worst case per view", "",
                "| View | Worst % | Case |", "|---|---:|---|"]
        for k in sorted(rows, key=lambda k: -rows[k][0]):
            out.append(f"| {k} | {rows[k][0]:.1f} | {rows[k][1]} |")
        out.append("")
    out += ["## How the numbers are measured", "",
            "See `tools/compare.py`. Peak: the largest load on the bottom control chart. "
            "Rising and post-peak: the largest distance between the two curves, measured both "
            "ways (Response's points from r2c's curve and r2c's from Response's), split at "
            "Response's peak; load scaled by Response's peak, control value by its largest value "
            "over the whole curve. An r2c point counts as post-peak when its nearest point on "
            "Response's curve is at or after Response's peak, so a response that runs on past "
            "Response's end, or stops short of it, shows as post-peak distance. "
            "Views: at each feature stage of Response's curve (cracking, falls of load, peak, "
            "last stage) and r2c's stage nearest it in load and control value, the largest "
            "distance of Response's points from r2c's curve, relative to the chart's largest "
            "value. Shape: the curve's features in order (cracking, falls of load before the "
            "peak, the peak, how the response ends), read alike from both curves; it matches "
            "when they are the same. Stage counts are not compared.", ""]
    return "\n".join(out)


def add_curves(results: dict, vo: Path) -> None:
    """Put r2c's curve on each case's compared control chart into its result (sub_curve)."""
    import compare as cmp
    from r2c import record

    for name, r in results.items():
        p = vo / f"{name}.r2x.txt"
        if not r.get("control") or not p.exists():
            continue
        lines = cmp.parse_chart(record.read(p).control(r["control"][-1]["chart"]))[3]
        if lines:
            r["sub_curve"] = [[round(float(x), 5), round(float(y), 4)] for x, y in lines[0]]


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("verify_out")
    ap.add_argument("--acceptance", default=str(ROOT / "docs" / "acceptance.md"))
    ap.add_argument("--out", default=str(ROOT / "docs" / "verification-results.md"))
    a = ap.parse_args(argv)
    vo = Path(a.verify_out)
    results = json.loads((vo / "results.json").read_text())
    run = json.loads((vo / "run.json").read_text())
    add_curves(results, vo)
    acc = read_acceptance(Path(a.acceptance))
    acc_rel = Path(a.acceptance).resolve()
    acc_path = str(acc_rel.relative_to(ROOT)) if ROOT in acc_rel.parents else str(acc_rel)
    out = Path(a.out)
    out.write_text(render(results, run, acc, acc_path), encoding="utf-8")
    out.with_suffix(".json").write_text(json.dumps({"run": run, "results": results}, indent=1))
    print(f"wrote {out} and {out.with_suffix('.json').name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
